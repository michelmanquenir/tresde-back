-- Catálogo de accesorios (argollas de llavero, mecanismos de clicker, imanes…) con su costo unitario.
CREATE TABLE accessories (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(80) NOT NULL UNIQUE,
    cost       INTEGER     NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

-- Accesorios que lleva cada pieza (y cuántos de cada uno)
CREATE TABLE product_accessories (
    product_id   VARCHAR(140) NOT NULL REFERENCES products (id) ON DELETE CASCADE,
    accessory_id BIGINT       NOT NULL REFERENCES accessories (id) ON DELETE CASCADE,
    quantity     INTEGER      NOT NULL,
    PRIMARY KEY (product_id, accessory_id)
);

-- Migra el antiguo "costo de accesorios" ($) de cada producto: se crea un accesorio por cada monto
-- distinto (ej. "Accesorio de $30"); después se puede renombrar desde el panel.
INSERT INTO accessories (name, cost, created_at)
SELECT DISTINCT CONCAT('Accesorio de $', CAST(accessories_cost AS VARCHAR(12))), accessories_cost, CURRENT_TIMESTAMP
FROM products WHERE accessories_cost > 0;

INSERT INTO product_accessories (product_id, accessory_id, quantity)
SELECT p.id, a.id, 1
FROM products p JOIN accessories a ON a.cost = p.accessories_cost
WHERE p.accessories_cost > 0;

ALTER TABLE products DROP COLUMN accessories_cost;
