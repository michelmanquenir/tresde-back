-- Ventas registradas desde el panel. Se guarda una "foto" del producto al momento de vender
-- (nombre, precio, costo, % máquina) para que el historial no cambie si después se edita o borra.
CREATE TABLE sales (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       VARCHAR(140),               -- sin FK: la venta se conserva aunque se borre o reimporte el producto
    product_name     VARCHAR(120) NOT NULL,
    category_slug    VARCHAR(40),
    color            VARCHAR(7),
    quantity         INTEGER NOT NULL,
    unit_price       INTEGER NOT NULL,
    unit_cost        DOUBLE PRECISION,          -- null si el producto no tenía datos de costo
    reserve_percent  DOUBLE PRECISION NOT NULL,
    stock_discounted BOOLEAN NOT NULL,
    channel          VARCHAR(30),
    customer         VARCHAR(120),
    note             VARCHAR(500),
    sold_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    created_at       TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_sales_sold_at ON sales (sold_at);
CREATE INDEX idx_sales_product ON sales (product_id);
