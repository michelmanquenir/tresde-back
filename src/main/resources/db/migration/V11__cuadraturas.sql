-- Cuadratura semanal: se cierran las ventas pendientes y se registra cuánto se retiró
-- (ganancia y máquina) y cuánto se reinvirtió en materia prima.
-- Lo retirado para la máquina se descuenta de su valor (machine_price) hasta pagarla.
ALTER TABLE cost_settings ADD COLUMN machine_price INTEGER NOT NULL DEFAULT 1300000;

CREATE TABLE closings (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    period_from          TIMESTAMP WITH TIME ZONE,          -- primera venta incluida
    period_to            TIMESTAMP WITH TIME ZONE NOT NULL, -- corte (fin del domingo)
    sales_count          INTEGER          NOT NULL,
    units                INTEGER          NOT NULL,
    revenue              DOUBLE PRECISION NOT NULL,
    materials            DOUBLE PRECISION NOT NULL,         -- calculado: materia prima
    machine              DOUBLE PRECISION NOT NULL,         -- calculado: % para la máquina
    profit               DOUBLE PRECISION NOT NULL,         -- calculado: ganancia
    materials_reinvested DOUBLE PRECISION NOT NULL,         -- lo que realmente se movió
    machine_withdrawn    DOUBLE PRECISION NOT NULL,
    profit_withdrawn     DOUBLE PRECISION NOT NULL,
    note                 VARCHAR(500),
    created_by           VARCHAR(255),
    created_at           TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_closings_period_to ON closings (period_to);

ALTER TABLE sales ADD COLUMN closing_id BIGINT REFERENCES closings (id) ON DELETE SET NULL;
CREATE INDEX idx_sales_closing ON sales (closing_id);
