-- Entregas de inventario: alguien entrega unidades (ej. 10 llaveros) a otro usuario del panel.
-- El stock recién se suma cuando quien recibe la acepta.
CREATE TABLE deliveries (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender_username    VARCHAR(255) NOT NULL,
    sender_name        VARCHAR(255) NOT NULL,
    recipient_username VARCHAR(255) NOT NULL,
    recipient_name     VARCHAR(255) NOT NULL,
    status             VARCHAR(20)  NOT NULL,             -- PENDING, ACCEPTED, REJECTED, CANCELLED
    note               VARCHAR(500),
    delivered_at       TIMESTAMP WITH TIME ZONE NOT NULL,  -- día en que se entregó
    resolved_at        TIMESTAMP WITH TIME ZONE,           -- cuándo se aceptó / rechazó / canceló
    resolved_by        VARCHAR(255),
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_deliveries_recipient ON deliveries (recipient_username, status);
CREATE INDEX idx_deliveries_sender ON deliveries (sender_username);

-- Detalle: qué productos y cuántas unidades
CREATE TABLE delivery_items (
    delivery_id  BIGINT       NOT NULL REFERENCES deliveries (id) ON DELETE CASCADE,
    position     INTEGER      NOT NULL,
    product_id   VARCHAR(140) REFERENCES products (id) ON DELETE SET NULL,
    product_name VARCHAR(255) NOT NULL,
    quantity     INTEGER      NOT NULL,
    PRIMARY KEY (delivery_id, position)
);
CREATE INDEX idx_delivery_items_product ON delivery_items (product_id);

-- Historial y comentarios de cada entrega
CREATE TABLE delivery_comments (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    delivery_id     BIGINT       NOT NULL REFERENCES deliveries (id) ON DELETE CASCADE,
    author_username VARCHAR(255) NOT NULL,
    author_name     VARCHAR(255) NOT NULL,
    body            VARCHAR(500) NOT NULL,
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_delivery_comments_delivery ON delivery_comments (delivery_id, created_at);
